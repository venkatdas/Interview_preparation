// Regenerates INDEX.md (topic + problem index), PROGRESS.md and PROBLEM_TRACKER.md from the folder tree.
// Usage: npm run index
// PROGRESS.md and PROBLEM_TRACKER.md keep your existing ticks/notes: rows are matched by link and preserved.
const fs = require('node:fs');
const path = require('node:path');
const { ROOT } = require('./_discover');

const isDir = p => fs.existsSync(p) && fs.statSync(p).isDirectory();
const nice = name => name.replace(/^\d+_/, '').replace(/_/g, ' ');

function firstHeading(file) {
  if (!fs.existsSync(file)) return null;
  const m = fs.readFileSync(file, 'utf8').match(/^#\s+(.+)$/m);
  return m ? m[1].trim() : null;
}

/** Leaf topic = folder that has 01_Concepts or 03_Problems. Parent topic = folder whose children are topics. */
function collect(dir, depth = 0, out = []) {
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (!/^\d\d_/.test(name) || !isDir(full)) continue;
    const isLeaf = isDir(path.join(full, '01_Concepts')) || isDir(path.join(full, '03_Problems'));
    const node = { name, full, rel: path.relative(ROOT, full), depth, isLeaf, problems: [], children: [] };
    if (isLeaf) node.problems = problemsOf(full);
    out.push(node);
    node.children = collect(full, depth + 1, []).filter(c => /^\d\d_/.test(c.name));
    // only treat numbered children that are not standard sections as sub-topics
    node.children = node.children.filter(c => !['01_Concepts', '02_Implementations', '03_Problems', '04_Interview_And_Assessment'].includes(c.name));
  }
  return out;
}

function problemsOf(topicDir) {
  const res = [];
  const pdir = path.join(topicDir, '03_Problems');
  if (!isDir(pdir)) return res;
  (function walk(d) {
    for (const name of fs.readdirSync(d).sort()) {
      const f = path.join(d, name);
      if (isDir(f)) { if (name !== 'solutions') walk(f); continue; }
      if (!name.endsWith('.md') || name === 'README.md') continue;
      const text = fs.readFileSync(f, 'utf8');
      const title = (text.match(/^#\s+(.+)$/m) || [, name])[1].trim();
      const diff = (text.match(/\*\*Difficulty\*\*\s*\|\s*([^|\n]+)/) || [, ''])[1].trim()
        || (/01_Easy/.test(f) ? 'Easy' : /03_Hard/.test(f) ? 'Hard' : /02_Medium/.test(f) ? 'Medium' : '');
      const pattern = (text.match(/\*\*Pattern\*\*\s*\|\s*([^|\n]+)/) || [, ''])[1].trim();
      res.push({ title, diff, pattern, rel: path.relative(ROOT, f) });
    }
  })(pdir);
  return res;
}

const tree = collect(ROOT);
const flat = [];
(function f(nodes) { for (const n of nodes) { flat.push(n); f(n.children); } })(tree);
const leaves = flat.filter(n => n.isLeaf);
const allProblems = leaves.flatMap(l => l.problems.map(p => ({ ...p, topic: l.rel })));

// ---------- INDEX.md ----------
let idx = `# Topic & Problem Index\n\nGenerated by \`npm run index\`. ${leaves.length} topics, ${allProblems.length} problems.\n\n## Topics\n\n`;
for (const n of flat) {
  const indent = '  '.repeat(n.depth);
  const readme = path.join(n.rel, 'README.md');
  const count = n.isLeaf ? ` — ${n.problems.length} problems` : '';
  idx += `${indent}- [${nice(n.name)}](${fs.existsSync(path.join(ROOT, readme)) ? readme : n.rel})${count}\n`;
}
idx += `\n## All problems by topic\n`;
for (const l of leaves) {
  if (!l.problems.length) continue;
  idx += `\n### ${l.rel.split('/').map(nice).join(' › ')}\n\n| Problem | Difficulty | Pattern |\n|---|---|---|\n`;
  for (const p of l.problems) idx += `| [${p.title}](${p.rel}) | ${p.diff} | ${p.pattern} |\n`;
}
const byDiff = d => allProblems.filter(p => p.diff.startsWith(d)).length;
idx += `\n## Totals\n\n| Easy | Medium | Hard | Total |\n|---|---|---|---|\n| ${byDiff('Easy')} | ${byDiff('Medium')} | ${byDiff('Hard')} | ${allProblems.length} |\n`;
fs.writeFileSync(path.join(ROOT, 'INDEX.md'), idx);

// ---------- PROGRESS.md (preserve ticks) ----------
const progressFile = path.join(ROOT, 'PROGRESS.md');
const oldProgress = fs.existsSync(progressFile) ? fs.readFileSync(progressFile, 'utf8') : '';
const ticked = new Set(oldProgress.split('\n').filter(l => /- \[x\]/i.test(l)).map(l => l.replace(/- \[x\]/i, '- [ ]').trim()));
const box = line => (ticked.has(line.trim()) ? line.replace('- [ ]', '- [x]') : line);
let prog = `# Progress\n\nTick a box only when you meet the **mastery criteria** in [ROADMAP.md](ROADMAP.md): explain it, implement it from memory, solve an unseen variation, list edge cases, justify complexity.\nRe-run \`npm run index\` after new topics are added; your ticks are kept.\n\n`;
for (const l of leaves) {
  const t = l.rel;
  prog += `## ${t.split('/').map(nice).join(' › ')}\n\n`;
  const items = [
    `- [ ] ${t}: read [concepts](${t}/01_Concepts)`,
    `- [ ] ${t}: ran and re-implemented [implementations](${t}/02_Implementations) from memory`,
    `- [ ] ${t}: solved all Easy problems without hints`,
    `- [ ] ${t}: solved all Medium problems (hints allowed once)`,
    `- [ ] ${t}: attempted the Hard problems`,
    `- [ ] ${t}: passed the [quiz](${t}/04_Interview_And_Assessment/QUIZ.md) (80%+)`,
    `- [ ] ${t}: re-solved 3 problems after 1 week`,
    `- [ ] ${t}: **MASTERED**`,
  ].filter(line => {
    const m = line.match(/\]\(([^)]+)\)/);
    return !m || fs.existsSync(path.join(ROOT, m[1]));
  }).filter(line => !(/Easy|Medium|Hard/.test(line) && !l.problems.some(p => line.includes(p.diff || '~'))));
  prog += items.map(box).join('\n') + '\n\n';
}
fs.writeFileSync(progressFile, prog);

// ---------- PROBLEM_TRACKER.md (preserve filled rows) ----------
const trackerFile = path.join(ROOT, 'PROBLEM_TRACKER.md');
const oldTracker = fs.existsSync(trackerFile) ? fs.readFileSync(trackerFile, 'utf8') : '';
const oldRows = new Map();
for (const line of oldTracker.split('\n')) {
  const m = line.match(/^\| \[[^\]]*\]\(([^)]+)\)/);
  if (m) oldRows.set(m[1], line);
}
let tr = `# Problem Tracker\n\nFill one row each time you attempt a problem. Columns:\n- **Date** first attempt (YYYY-MM-DD), **Tries** number of attempts, **Solo** solved independently (Y/N), **Hints** how many hints you opened (0–4)\n- **Review 1/2/3** dates you re-solved it (spaced repetition: +3 days, +1 week, +1 month — see [the schedule](45_Revision_And_Spaced_Repetition/01_Concepts/SPACED_REPETITION_SCHEDULE.md))\n- **Notes** the key insight or the mistake you made\n\nRows are regenerated by \`npm run index\`; anything you typed in a row is kept.\n`;
for (const l of leaves) {
  if (!l.problems.length) continue;
  tr += `\n## ${l.rel.split('/').map(nice).join(' › ')}\n\n| Problem | Topic | Difficulty | Pattern | Date | Tries | Solo | Hints | Review 1 | Review 2 | Review 3 | Notes |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const p of l.problems) {
    tr += (oldRows.get(p.rel) || `| [${p.title}](${p.rel}) | ${nice(l.name)} | ${p.diff} | ${p.pattern} |  |  |  |  |  |  |  |  |`) + '\n';
  }
}
fs.writeFileSync(trackerFile, tr);

console.log(`INDEX.md, PROGRESS.md, PROBLEM_TRACKER.md written: ${leaves.length} topics, ${allProblems.length} problems`);
